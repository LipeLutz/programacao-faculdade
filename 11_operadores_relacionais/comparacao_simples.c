#include <stdio.h>

int main(){

    // Os operadores relacionais são usados para comparar valores, retornando 1 se a comparação for verdadeira, e 0 se for falsa

    int a = 10;
    int b = 20;

    printf("a > b: %d\n", a > b);
    printf("a < b: %d\n", a < b);
    printf("a == b: %d\n", a == b);
    printf("a != b: %d\n", a != b);

    return 0;
}